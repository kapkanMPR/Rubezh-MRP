        public static bool Has(StudioPlaced o)
        {
            return o != null && !o.Destroyed && Shapes.ContainsKey(o.Asset.Id);
        }

        public static bool Intercepts(Shape s, float u, float normal, float height)
        {
            if (Math.Abs(normal - .5f) > .12f)
                return false;
            if (s.Type == 2)
                return height <= 1f || height >= 2.2f && height <= 2.4f;
            if (s.Type == 3)
                return height >= 2.2f && height <= 2.4f;
            float pos = Math.Max(0f, Math.Min(1f, u)) * 64f;
            int i = Math.Min(63, (int)pos);
            return height <= (s.H[i] + (s.H[i + 1] - s.H[i]) * (pos - i)) * .01f;
        }

        public static bool TryBlock(StudioPlaced o, V2 point, float h, out bool block)
        {
            block = false;
            Shape s;
            if (o == null || o.Destroyed || !Shapes.TryGetValue(o.Asset.Id, out s))
                return false;
            bool x = s.X != o.Asset.Mirrored;
            float u = x ? (point.X - o.X) / o.Asset.Width : (point.Y - o.Y) / o.Asset.Height;
            if (o.Asset.Mirrored)
                u = 1 - u;
            block = Intercepts(s, u, x ? point.Y - o.Y : point.X - o.X, h);
            return true;
        }
